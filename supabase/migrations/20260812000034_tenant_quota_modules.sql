-- 0034 โควตากิจการ + โมดูลที่เปิดใช้ — ทำให้คอลัมน์ที่ 0025 สร้างไว้ "ใช้งานจริง"
--   (NEXT_STEPS 4.4 + 4.5 · คอลัมน์ max_entities / modules_enabled มีมาตั้งแต่ 0025
--    แต่ยังไม่มีโค้ดไหนอ่านเลยจนถึงตอนนี้)
--
--   🚨 ปัญหาที่ไฟล์นี้แก้: `max_entities` default = 1 ทุก tenant รวมถึงเจ้าที่มี
--      **หลายกิจการอยู่จริงแล้ว** (กิจการของเจ้าของระบบเอง = EID01 บริษัท + EID02 บุคคลธรรมดา)
--      → ถ้าโค้ดฝั่ง UI/สคริปต์เชื่อค่านี้ตรง ๆ จะกลายเป็น "มีข้อมูล 2 กิจการ แต่ระบบบอกว่าซื้อได้ 1"
--        = ซ่อนตัวเลือกกิจการทิ้ง แล้วเจ้าของเข้าถึงข้อมูล EID02 ไม่ได้อีกเลย
--      → ดันโควตาขึ้นให้ไม่น้อยกว่าจำนวนกิจการที่มีอยู่จริงเสียก่อน
--
--   ★ ไฟล์นี้ไม่แตะ RLS — policy tenants_sel (0025:193) เปิดให้อ่านแถวตัวเองได้อยู่แล้ว
--     และลูกค้าแก้ tenants ไม่ได้ (ไม่มี policy for update) = โควตา/โมดูลเลื่อนเองไม่ได้
-- ============================================================================

update tenants t
set max_entities = greatest(
      t.max_entities,
      (select count(*) from entities e where e.tenant_id = t.id)::int
    );

comment on column tenants.max_entities is
  'จำนวนกิจการสูงสุดที่ลูกค้ารายนี้สร้างได้ (add-on ขายแยก) '
  '⚠️ เป็นโควตาตอน "สร้าง" เท่านั้น — ห้ามเอาไปตัดสินว่าจะโชว์ตัวเลือกกิจการใน UI ไหม '
  'UI ต้องดูจากจำนวน entity ที่มีอยู่จริง ไม่งั้นลูกค้าที่มีหลายกิจการอยู่แล้วจะเข้าถึงข้อมูลไม่ได้';

comment on column tenants.modules_enabled is
  'โมดูลที่ลูกค้ารายนี้ซื้อ (production/accounting/sales) — ใช้ซ่อนเมนูและกันเข้าทาง URL '
  '⚠️ เป็น "สิทธิ์ตามแพ็กเกจ" ไม่ใช่ขอบเขตความปลอดภัย → ไม่ต้องบังคับที่ RLS '
  'และ **ห้ามปิดการเชื่อมข้ามโมดูลระดับ DB** (ขายแล้วลงบัญชีอัตโนมัติต้องทำงานต่อเสมอ)';

notify pgrst, 'reload schema';
