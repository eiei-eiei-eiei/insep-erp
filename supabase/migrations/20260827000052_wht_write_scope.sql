-- ============================================================================
-- 0052 อุดรูรั่ว: `for all` ครอบ SELECT ด้วย → ฝ่ายเงินเดือนเห็นใบ 50ทวิ ของคู่ค้า (D85)
--
-- 🚨 อาการ: `wht_sel` เขียนไว้ถูกแล้วว่าฝ่ายเงินเดือนเห็นเฉพาะแถวที่ `emp_id` ไม่ว่าง
--    แต่ `wht_w` เป็น `for all` ซึ่ง **ครอบ SELECT ด้วย** และ policy แบบ permissive
--    ถูก **OR กัน** → `has_cap('pay.write')` เลยเปิดอ่าน **ทุกแถว** ทับ policy ที่แคบกว่า
--    = ฝ่ายเงินเดือนเห็นว่ากิจการจ่ายค่าบริการให้คู่ค้ารายไหนเท่าไหร่
--
-- 🪤 บทเรียนทั่วไป: **`for all` ไม่ได้แปลว่า "สิทธิ์เขียน" — มันคือทุก command รวม select**
--    เขียน policy อ่านให้แคบแล้วยังรั่วได้ ถ้ามี policy `for all` ที่กว้างกว่าอยู่บนตารางเดียวกัน
--    ตารางอื่นในระบบรอด **โดยบังเอิญ** เพราะบทบาทที่มี `.write` มี `.read` ของโดเมนเดียวกันเสมอ
--    (ดู ROLE_CAPS) — ตารางนี้ตัวเดียวที่เงื่อนไขอ่านมีมิติเพิ่ม (`emp_id`) ที่ฝั่งเขียนไม่มี
--
-- ★ เจอตอนเทสในเบราว์เซอร์จริงทีละบทบาท — `test:tenant` รอบแรกไม่จับ เพราะยังไม่มีเคส
--   "ใส่ใบของคู่ค้าแล้วดูว่าฝ่ายเงินเดือนเห็นไหม" (เพิ่มเคสนั้นแล้วใน role-caps.test.ts)
-- ============================================================================

drop policy if exists wht_w on wht_certificates;

-- ★ ยกเงื่อนไข `emp_id` มาไว้ฝั่งเขียนด้วย — นอกจากอุดรูอ่านแล้ว ยังถูกกว่าเดิมในเชิงธุรกิจ:
--   ฝ่ายเงินเดือน**ไม่ควรแก้ใบ 50ทวิ ของคู่ค้า**อยู่แล้ว (คนละเรื่องกับงานของเขา)
create policy wht_w on wht_certificates for all
  using (
    tenant_id = my_tenant()
    and (has_cap('acct.write') or (has_cap('pay.write') and emp_id is not null))
  )
  with check (
    tenant_id = my_tenant()
    and (has_cap('acct.write') or (has_cap('pay.write') and emp_id is not null))
  );

comment on policy wht_w on wht_certificates is
  'ใบ 50ทวิ ของคู่ค้าและของพนักงานอยู่ตารางเดียวกัน — ฝ่ายเงินเดือนแตะได้เฉพาะแถวที่มี emp_id '
  '🚨 เงื่อนไข emp_id ต้องอยู่ทั้งใน wht_sel และ policy นี้ เพราะ for all ครอบ select ด้วย '
  'ใส่แค่ที่เดียวแล้วอีกที่กว้างกว่า = รั่วโดยไม่มีอะไรฟ้อง';

notify pgrst, 'reload schema';
