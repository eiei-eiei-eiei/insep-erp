--   คนของเจ้าหนึ่งพิมพ์ **ชื่อตัวเอง** ที่ URL ของอีกเจ้าแล้วเข้าได้เลย
--   โดยไม่ต้องรู้อะไรเกี่ยวกับเป้าหมายสักอย่าง — ชื่อ 'admin'/'owner' ซ้ำกันเป็นเรื่องปกติ
--
--   พอ username ไม่ซ้ำทั้งระบบ: พิมพ์ชื่อตัวเองที่ URL ไหนก็เข้าบัญชีตัวเอง
--   → ทางที่เกิดโดยบังเอิญปิดสนิท
--
--   ⚠️ ไม่ได้ปิดทุกทาง: ถ้ารู้ชื่อผู้ใช้ของอีกเจ้า + รหัสบังเอิญตรงกัน ยังเข้าได้
--      ทางนั้นปิดได้ด้วย MFA เท่านั้น — จดเป็นเงื่อนไขก่อนรับลูกค้ารายแรกใน NEXT_STEPS
--
--   ผลข้างเคียงที่ตั้งใจ: subdomain ไม่ต้องใช้แยกบัญชีอีกต่อไป
--   → กลับไปเป็น "ของแต่งหน้า" ล้วน ๆ ตามเจตนาเดิมใน NEXT_STEPS:181 · ระบบง่ายลง
--   → อีเมลภายในกลับเป็น <username>@insep.local เหมือนก่อนงาน multi-tenant
