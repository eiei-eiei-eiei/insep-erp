-- กันพังแบบงง ๆ: ถ้ามีชื่อซ้ำอยู่จริงต้องบอกว่าซ้ำชื่อไหน ไม่ใช่โยน unique_violation เปล่า ๆ
do $$
declare dups text;
begin
  select string_agg(username || ' (' || n || ' บัญชี)', ', ')
    into dups
  from (select username, count(*) n from profiles group by username having count(*) > 1) x;

  if dups is not null then
    raise exception E'มีชื่อผู้ใช้ซ้ำข้ามกิจการอยู่ ต้องแก้ก่อน: %\n'
      '  เปลี่ยนชื่อให้ไม่ซ้ำก่อน แล้วค่อยรัน migration นี้ใหม่', dups;
  end if;
end $$;

alter table profiles drop constraint if exists profiles_username_key;
alter table profiles add constraint profiles_username_key unique (username);

comment on column profiles.username is
  'ชื่อผู้ใช้ — unique ทั้งระบบ (ไม่ใช่ต่อกิจการ) เพื่อกันคนของกิจการหนึ่งพิมพ์ชื่อตัวเอง '
  'ที่ URL ของอีกกิจการแล้วเข้าได้เมื่อรหัสผ่านบังเอิญตรงกัน';

