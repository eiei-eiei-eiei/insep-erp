-- 0081 · D108 — บาร์: จัดลำดับเมนูเอง ▲▼ แยกกันต่อหน้า
--
-- ผู้ใช้ขอ: เอาเมนูที่สั่งบ่อยมาไว้บนสุดของหน้าขาย ไม่ต้องเลื่อนหา
-- ผู้ใช้เลือก: **ลำดับของแต่ละหน้าตั้งแยกกัน ไม่มีผลต่อกัน** (หน้า "ทั้งหมด" กับแต่ละหมวด)
--
-- ★ ไม่ต้องมีตารางใหม่:
--   · ลำดับ **ในหมวด** = `bar_menu.sort` เดิม — เมนูหนึ่งอยู่ได้หมวดเดียว ⇒ แต่ละหมวดเป็นชุดที่ไม่ทับกัน
--     ลำดับของหมวดหนึ่งจึงไม่มีทางกระทบอีกหมวดอยู่แล้ว
--   · ลำดับ **หน้า "ทั้งหมด"** = คอลัมน์ใหม่ `sort_all` (หน้าเดียวที่เมนูทุกหมวดมาอยู่รวมกัน)
--
-- 🚨 backfill `sort_all = sort` — ไม่งั้นวันที่ลง migration หน้า "ทั้งหมด" ของลูกค้าทุกเจ้าจะเรียงใหม่เองทั้งหน้า
--    (บาร์เทนเดอร์จำตำแหน่งเมนูไว้แล้ว) · ค่าว่าง = ต่อท้ายตามชื่อ (เหมือน sort ว่างในหมวด)
-- ★ เขียนผ่าน RLS เดิมของ bar_menu (`bar.write` · 0064) เหมือนการเรียงหมวด D101 — ไม่มี RPC ใหม่
--   คอลัมน์เพิ่มไม่ต้องแตะ `fn_bar_save_menu` (มัน update เฉพาะคอลัมน์ที่ระบุ ไม่ล้าง sort/sort_all)

alter table bar_menu add column if not exists sort_all int;

-- 🪤 ปิด user trigger ระหว่าง backfill (บทเรียน D50) — audit_bar_menu จะจด edit_log ทุกแถว
--    ทั้งที่ไม่มีใครแก้อะไร แล้วหน้า "ประวัติการแก้ไข" จะเต็มไปด้วยแถวที่ผู้ใช้ไม่ได้ทำ
alter table bar_menu disable trigger user;
update bar_menu set sort_all = sort where sort_all is null and sort is not null;
alter table bar_menu enable trigger user;
