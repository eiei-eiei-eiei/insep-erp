/**
 * lib/bar/customerName — ชื่อลูกค้าบาร์ที่แสดง **บนจอ** (golden B15 · D97)
 *
 * ── 🚨 เส้นแบ่งที่ห้ามข้าม: จอ ≠ กระดาษ ──────────────────────────────────
 * **บนจอ** คนหลังบาร์จำลูกค้าด้วยชื่อเล่น ("พี่โอ๊ต") ไม่ใช่ชื่อในบัตรประชาชน
 * **บนกระดาษ** ใบเสร็จ/ใบกำกับภาษีต้องเป็น **ชื่อจริงล้วน** ตามที่ลูกค้าให้มา
 * ⇒ ไฟล์นี้ถูกเรียกจากคอมโพเนนต์เท่านั้น · `receipt.ts` / `print80.ts`
 *   **ห้าม import ไฟล์นี้เด็ดขาด** (มีเทสอ่านซอร์สมาตรวจใน `customerName.test.ts`)
 *
 * ── ทำไมต้องมีไฟล์เดียว ───────────────────────────────────────────────────
 * ก่อนหน้านี้แต่ละหน้าจอเลือกเอง: ดร็อปดาวน์ใช้ `nickname || name` ·
 * ชิปกรองเมนูกับแดชบอร์ดใช้ `name` · ทะเบียนลูกค้าใช้ `name (nickname)`
 * ⇒ ลูกค้าคนเดียวมีชื่อ 3 แบบใน 3 หน้าจอที่อยู่ห่างกันไม่ถึงหนึ่งจอ
 */

export type CustomerNameInput = {
  name?: string | null;
  nickname?: string | null;
};

export type CustomerNameParts = {
  /** ตัวเด่น — ชื่อเล่นถ้ามี */
  head: string;
  /** ตัวในวงเล็บ (ชื่อจริง) — `null` = ไม่ต้องมีวงเล็บ */
  paren: string | null;
};

/**
 * แยกเป็น 2 ท่อน ให้คอมโพเนนต์จัดสไตล์เองได้ (ตัวเด่น/ตัวจาง)
 *
 * 🚨 **ไม่มีวงเล็บว่างเด็ดขาด** — ผู้ใช้บอกเองว่าลูกค้าทั่วไปจะพิมพ์ชื่อเล่นลงช่อง
 *    *ชื่อ* ไปเลยเพราะไม่ขอใบกำกับอยู่แล้ว ⇒ `nickname` ว่างคือ **เคสปกติ ไม่ใช่ข้อมูลขาด**
 *    ปล่อยให้ขึ้น `พี่โอ๊ต ()` = หน้าจอดูเหมือนข้อมูลพัง
 * 🪤 กรอกชื่อเล่นซ้ำกับชื่อจริง → แสดงครั้งเดียว (`พี่โอ๊ต` ไม่ใช่ `พี่โอ๊ต (พี่โอ๊ต)`)
 * 🪤 ชื่อจริงว่างแต่มีชื่อเล่น → ใช้ชื่อเล่นเป็นตัวเด่น ไม่ใช่คืนค่าว่าง
 *    (แถวแบบนี้ไม่ควรมี เพราะฟอร์มบังคับชื่อ แต่ข้อมูลเก่า/นำเข้ามีได้)
 */
export function customerNameParts(c: CustomerNameInput | null | undefined): CustomerNameParts {
  const name = String(c?.name ?? "").trim();
  const nick = String(c?.nickname ?? "").trim();
  if (!nick) return { head: name, paren: null };
  if (!name || name === nick) return { head: nick, paren: null };
  return { head: nick, paren: name };
}

/**
 * ข้อความบรรทัดเดียว — ใช้ตรงที่จัดสไตล์ไม่ได้ (`<option>` · ป้าย · ข้อความในประโยค)
 * ★ ไม่มีข้อมูลเลย → คืนค่าว่าง **ห้ามคืน "—" หรือ "ไม่ระบุ"**
 *   คำแทนที่ควรใช้ขึ้นกับบริบทของแต่ละหน้าจอ ไม่ใช่ของฟังก์ชันนี้
 */
export function customerLabel(c: CustomerNameInput | null | undefined): string {
  const { head, paren } = customerNameParts(c);
  return paren ? `${head} (${paren})` : head;
}
