/**
 * lib/sales/cashAccount — บัญชีที่การรับเงินของแอปขายลง (D142 · golden S14)
 *
 * เงินสดเข้าธนาคารจริงตอนเอาไปฝาก ไม่ใช่ตอนขาย (คนละวัน · รวมก้อน · อาจหยิบไปใช้ก่อน)
 * ⇒ ถ้ารับเงินสดแล้วลงบัญชีธนาคาร สเตทเม้นต์จะไม่มีวันตรง
 * → ตั้ง **บัญชีเงินสด** แยกได้ แล้วตอนฝากค่อยบันทึก "โอนเงินระหว่างบัญชี"
 *
 * ★ แพตเทิร์นเดียวกับบาร์ (`lib/bar/payMethods.ts` · D116) แต่แอปขายตัดสินฝั่ง TS ที่เดียว
 *   (`fn_apply_order_action` เขียน account_name ตามที่ได้รับ) ⇒ ไม่มีกติกาซ้ำใน SQL
 * 🚨 ไม่ตั้ง = ทุกวิธีลงบัญชีหลัก (พฤติกรรมเดิมทุกตัวอักษร)
 * 🚨 ประโยคบนจอตัดสินที่นี่ ไม่ใช่ในคอมโพเนนต์ (D84/D91)
 */

export const CASH_METHOD = "เงินสด";

/**
 * บัญชีที่การรับเงินครั้งนี้จะลง — **จุดเดียว** ที่ตัดสินเรื่องนี้ในแอปขาย
 * · วิธีอื่น (โอนเงิน/บัตรเครดิต/เช็ค) สุดท้ายเข้าธนาคาร ⇒ บัญชีหลัก
 * ★ แต่ละครั้งที่รับเงินตัดสินจากวิธีของครั้งนั้น (มัดจำเงินสด + ยอดค้างโอน = ลงคนละบัญชี)
 */
export function revenueAccountFor(
  method: string | undefined,
  config: { accountName: string; cashAccountName?: string },
): string {
  const cash = (config.cashAccountName ?? "").trim();
  return (method ?? "").trim() === CASH_METHOD && cash ? cash : config.accountName;
}

/** คำอธิบายใต้ช่องตั้งค่า — บอกว่าตอนนี้เงินสดจะไปลงที่ไหน และต้องทำอะไรต่อ */
export function cashSettingText(accountName: string, cashAccountName: string): string {
  const cash = cashAccountName.trim();
  const main = accountName.trim();
  if (!cash || cash === main) {
    return main
      ? `ตอนนี้รับเงินสดแล้วลงบัญชี "${main}" เหมือนเงินโอน — ถ้าเงินสดไม่ได้เข้าธนาคารทันที ยอดในแอปจะไม่ตรงกับสเตทเม้นต์ ให้เลือกบัญชีเงินสดแยก`
      : "ไม่เลือก = รับเงินสดแล้วลงบัญชีเดียวกับเงินโอน";
  }
  return `รับเงินสดลงบัญชี "${cash}" · โอนเงิน/บัตรเครดิต/เช็ค ลงบัญชีหลัก — ตอนเอาเงินสดไปฝาก ให้บันทึกที่ บัญชี → บัญชี & เงินสด → โอนเงินระหว่างบัญชี ด้วยวันที่และยอดที่ฝากจริง`;
}
