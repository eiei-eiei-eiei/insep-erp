/**
 * lib/sales/productionText — ประโยคในแอปขายที่พูดถึง "สุรา / ฟอร์ม ภส. / โรงกลั่น" (D133)
 *
 * แอปขายเกิดมาคู่กับโรงกลั่น ประโยคหลายจุดจึงพูดถึงสุราตลอด · ลูกค้าที่ซื้อแค่ขาย (ไม่มีโมดูลผลิต)
 * อ่านแล้วงงว่า "ภส." คืออะไร → ไม่มีโมดูลผลิต = ใช้ประโยคกลาง
 * ★ ประโยคตัดสินที่นี่ (มีเทสคุม) ไม่ใช่ในคอมโพเนนต์ (D84/D91)
 * 🚨 เปลี่ยนแค่ข้อความ — ไม่แตะการตัดสต็อก/การส่งข้อมูลเข้าแอปผลิต (เมนูหมวด "สุรา" ที่ตั้งไว้แล้วยังทำงานเหมือนเดิม)
 */
export type SalesProductionText = {
  /** หมวดเมนูปริยายตอนเพิ่มเมนูใหม่ */
  defaultMenuCategory: "สุรา" | "ทั่วไป";
  /** ป๊อปอัพยืนยันจัดส่ง */
  shipConfirm: string;
  /** ใต้ฟอร์มปรับสต็อกคลังมือ — null = ไม่มีอะไรต้องบอก */
  manualStockNote: string | null;
  /** หัวการ์ดสต็อกรวมในแท็บคลัง */
  stockTitle: string;
  /** ใต้ปุ่มขายหน้าร้าน (ลงรายการย้อนหลัง) */
  posBackdate: string;
  /** ช่องติ๊กลูกค้าต่างประเทศ */
  exportLabel: string;
};

export function salesProductionText(hasProduction: boolean): SalesProductionText {
  return hasProduction
    ? {
        defaultMenuCategory: "สุรา",
        shipConfirm: "ระบบจะตัดสต็อกทันที · สุราจะขึ้นฟอร์ม ภส. เป็นการจ่ายของวันที่ด้านล่าง",
        manualStockNote: "สุราตัดสต็อกอัตโนมัติจากการขาย (ผ่านแอปผลิต) — ปรับ manual ได้เฉพาะสินค้าทั่วไป",
        stockTitle: "สต็อกรวม (สุราจากโรงกลั่น + สินค้าทั่วไป)",
        posBackdate: "ระบบล่มในวันที่ขาย? ติ๊ก “ลงรายการย้อนหลัง” ด้านบน — เลขใบเสร็จ บัญชี และฟอร์ม ภส. จะเป็นของวันนั้น",
        exportLabel: "— ส่งข้อมูลให้แอปผลิตเป็น “จำหน่ายต่างประเทศ”",
      }
    : {
        defaultMenuCategory: "ทั่วไป",
        shipConfirm: "ระบบจะตัดสต็อกทันที เป็นการส่งของวันที่ด้านล่าง",
        manualStockNote: null,
        stockTitle: "สต็อกสินค้า",
        posBackdate: "ระบบล่มในวันที่ขาย? ติ๊ก “ลงรายการย้อนหลัง” ด้านบน — เลขใบเสร็จและบัญชีจะเป็นของวันนั้น",
        exportLabel: "— ผู้ซื้ออยู่ต่างประเทศ",
      };
}

/**
 * หมวดเมนูที่ให้เลือก — ไม่มีโมดูลผลิต = ไม่มี "สุรา (ตัดสต็อกผลิต)" (ไม่มีสต็อกผลิตให้ตัด)
 * ★ `current` = หมวดของเมนูที่กำลังแก้ ต้องอยู่ในลิสต์เสมอ (ไม่งั้น Select โชว์ผิดแล้วบันทึกทับเงียบ ๆ · D125)
 */
export function menuCategoryOptions(hasProduction: boolean, current?: string): { value: string; label: string }[] {
  const out = [{ value: "ทั่วไป", label: "ทั่วไป (ตัดสต็อกคลัง)" }];
  if (hasProduction || current === "สุรา") out.unshift({ value: "สุรา", label: "สุรา (ตัดสต็อกผลิต)" });
  return out;
}
