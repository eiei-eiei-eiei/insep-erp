/**
 * แปล error จาก Postgres/Supabase เป็นข้อความไทยที่ผู้ใช้ (เขียนโค้ดไม่ได้) เข้าใจ
 * ใช้แทน `fail(error.message)` ที่คืน SQLSTATE ดิบเป็นภาษาอังกฤษ
 * code = SQLSTATE ของ Postgres · ถ้าไม่รู้จัก คืน message เดิม (RPC ที่ raise มักเป็นไทยอยู่แล้ว)
 */
export function mapDbError(err: { code?: string | null; message?: string | null } | null | undefined): string {
  const code = err?.code ?? "";
  const msg = err?.message || "เกิดข้อผิดพลาด";
  switch (code) {
    // ── ฝั่งเขียน ──────────────────────────────────────────────────────────
    case "23505": return "มีข้อมูลนี้อยู่แล้ว (ชื่อ/เลขที่ซ้ำ) — ตรวจแล้วลองใหม่";
    case "23503": return "ลบไม่ได้ — มีรายการอื่นอ้างอิงข้อมูลนี้อยู่";
    case "23502": return "ข้อมูลไม่ครบ — มีช่องบังคับที่ยังว่าง";
    case "23514": return "ค่าที่กรอกไม่ถูกต้องตามที่ระบบกำหนด";
    case "42501": return "สิทธิ์ไม่พอ — ต้องเป็นผู้ใช้ระดับ main ถึงจะทำรายการนี้ได้";
    // ── ฝั่งอ่าน (D89) — โค้ดชุดนี้ไม่เคยถูก map เพราะไม่มีใครอ่าน error ตอน query ──
    //    ปล่อยไว้จะได้ข้อความอังกฤษดิบขึ้นจอให้ผู้ใช้ที่เขียนโค้ดไม่ได้
    case "42P01": return "ระบบยังไม่พร้อม — ยังไม่ได้ติดตั้งตารางข้อมูลนี้ (แจ้งผู้ดูแลระบบ)";
    case "42703": return "ระบบยังไม่พร้อม — โครงข้อมูลไม่ตรงกับเวอร์ชันของแอป (แจ้งผู้ดูแลระบบ)";
    case "22008": return "ช่วงวันที่ไม่ถูกต้อง — ตรวจเดือน/ปีที่เลือกแล้วลองใหม่";
    case "57014": return "ใช้เวลานานเกินไป ระบบยกเลิกให้ — ลองแคบช่วงเดือนลงแล้วลองใหม่";
    case "PGRST103": return "ช่วงข้อมูลที่ขอไม่ถูกต้อง — ลองใหม่อีกครั้ง";
    case "P0001": return msg; // RAISE จาก RPC — เป็นข้อความไทยอยู่แล้ว
    default: return msg;
  }
}

/** ผลลัพธ์ของ query จาก supabase-js เท่าที่ `mustRead` ต้องใช้ */
export type ReadResult<T> = { data: T | null; error: { code?: string | null; message?: string | null } | null };

/**
 * ค่าที่อ่านมาได้ — **`error` แปลว่าโยนทิ้ง ห้ามคืนลิสต์ว่าง** (D89)
 *
 * ทำไมต้องมี: ทั้งชั้นอ่านเขียน `const { data } = await q` แล้วทิ้ง `error` ไป
 * → query พังเมื่อไหร่ผู้ใช้เห็น "— ไม่มีรายการ —" ซึ่งอ่านได้ว่า *ไม่มีข้อมูล* ไม่ใช่ *โหลดไม่สำเร็จ*
 * และรายงานยื่นราชการก็ขาดแถวเงียบ ๆ แล้วยื่นออกไปโดยไม่มีใครรู้
 *
 * ★ ยึดแพตเทิร์นเดียวกับ `fetchAllRows` (lib/shared/paginate.ts) ที่ throw อยู่แล้วพร้อมเหตุผลว่า
 *   *"ถ้าได้ไม่ครบให้ throw ดีกว่าปล่อยเลขผิดไปขึ้นรายงานภาษี"* — งานนี้คือทำให้ทั่วถึง ไม่ใช่คิดใหม่
 *
 * 🪤 **`data: null` ที่ไม่มี error ต้องไม่ throw** — `.maybeSingle()` คืน `null` ตอนไม่เจอแถวเป็นเรื่องปกติ
 *    (ถ้า throw ด้วย จะกลายเป็น "ไม่เจอ = พัง" ซึ่งผิดคนละเรื่อง)
 *
 * 🚨 ผู้เรียกฝั่ง UI ต้องมีที่รับ throw เสมอ (hook `useRead` หรือ server component ที่มี error.tsx)
 *    ไม่งั้นจะกลายเป็น unhandled rejection = ค้างที่ "กำลังโหลด…" ซึ่งแย่กว่าลิสต์ว่าง
 */
export function mustRead<T>(res: ReadResult<T>, label: string): T {
  if (res.error) throw new Error(`โหลด${label}ไม่สำเร็จ — ${mapDbError(res.error)}`);
  return res.data as T;
}
