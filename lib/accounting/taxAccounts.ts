/**
 * ชุดบัญชีที่ "มีผลจริง" — `saved` คือที่ผู้ใช้ตั้งเอง · `bankNames` คือบัญชีเงินทั้งหมดในระบบ
 *
 * 🚨 มี `saved` เมื่อไหร่ใช้ `saved` เท่านั้น ห้ามเอามารวมกับ `bankNames`
 *    (รวม = คัดบัญชีส่วนตัวออกไม่ได้เลย ซึ่งคือเหตุผลทั้งหมดที่ตั้งค่านี้มีอยู่)
 */
export function effectiveTaxAccounts(saved: string[], bankNames: string[]): Set<string> {
  const clean = (xs: string[]) => xs.map((x) => String(x ?? "").trim()).filter(Boolean);
  const set = clean(saved);
  return new Set(set.length > 0 ? set : clean(bankNames));
}

/** ตั้งเองหรือยัง — ใช้ตัดสินข้อความบนหน้าจอ (ห้ามให้ค่าปริยายไปโผล่เป็น chip ที่ลบได้ · D80) */
export function taxAccountsAreDefault(saved: string[]): boolean {
  return saved.map((x) => String(x ?? "").trim()).filter(Boolean).length === 0;
}
